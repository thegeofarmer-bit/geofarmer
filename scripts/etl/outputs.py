from __future__ import annotations

from rasterio.shutil import copy as rio_copy

from .common import CONTEXT_GDB, OUT, SRC, fixes, gaps, read, write_geojson


def context_layers() -> None:
    gaps.append("District boundary: `District/Ejura.shp` is byte-identical to `FARMS/New.shp` (30 farm polygons), "
                "not the Ejura-Sekyedumase municipal boundary. Not exported; please supply the real boundary.")
    write_geojson(read(CONTEXT_GDB, "River"), "rivers")
    write_geojson(read(CONTEXT_GDB, "Road"), "roads")


def cogs() -> None:
    for name in ("dem", "slope"):
        rio_copy(SRC / name, OUT / "rasters" / f"{name}_cog.tif", driver="COG", compress="DEFLATE")
        (OUT / "rasters" / f"{name}_cog.tif.aux.xml").unlink(missing_ok=True)
    fixes.append("Rasters: DEM and slope converted from ArcInfo Grid (.adf) to Cloud-Optimized GeoTIFF.")


def report(counts: dict[str, int]) -> None:
    lines = ["# GeoFarmer data extraction report", "",
             "Generated by `scripts/extract_arcgis.py` from `NASA SPACE APPS/` (sources untouched).", "",
             "## Outputs", "", "| File | Rows |", "|---|---|"]
    lines += [f"| `{k}` | {v} |" for k, v in counts.items()]
    lines += ["", "## Fixes applied", ""] + [f"- {f}" for f in fixes]
    lines += ["", "## Remaining gaps (need the GIS / agronomy team)", ""] + [f"- {g}" for g in gaps]
    (OUT / "REPORT.md").write_text("\n".join(lines) + "\n")
